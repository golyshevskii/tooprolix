"""
One-shot prose measurement over the pinned corpus in `corpus.lock`.

Research script, not product code: Python + stdlib only (`ast`, `tokenize`,
`difflib`, `dataclasses`). Zero third-party imports on purpose — AC4 (a re-run
must be byte-identical) must not depend on dependency resolution. The product
is Rust and lives elsewhere.

Usage:
    uv run python3 corpus/measure.py --lock corpus/corpus.lock

Stdout is the report and is deterministic: sorted iteration everywhere, no
timestamps, no absolute paths, fixed float formatting. Diagnostics go to stderr.

Determinism is per-interpreter, and that is enforced, not hoped for: see
MIN_INTERPRETER below. Measured on CPython 3.14.6 (Darwin 25.5.0, arm64).
"""

