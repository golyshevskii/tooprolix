# The restatement probe reads NAME tokens off the code line under a comment, and PEP 701
# (Python 3.12) changed what those are: before 3.12 an f-string was ONE STRING token, so every
# identifier interpolated inside it was invisible. Measured on an audited repository, same commit,
# same block count (2033 blocks, 1035 comment blocks) — only the probe moves:
#     3.11  -> 137 restatement candidates is reported as 133, code-like 21 as 19
#     3.12+ -> 137 / 21   (identifiers inside f-strings are seen, which is the faithful reading)
# So AC4 byte-identity holds on a FIXED interpreter and not across versions. Rather than let a
# 3.11 run quietly emit different constants into REPORT.md, refuse to run at all.
